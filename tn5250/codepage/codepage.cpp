CodePage::CodePage(ID id) : m_id(id) {
    m_toUnicode.fill(0x0000);
    for (int i = 0; i < 0x40; ++i) {
        m_toUnicode[i] = static_cast<uint16_t>(i);
    }
    m_toUnicode[0x40] = 0x0020;

    switch (id) {
    case ID::CP037: initCP037(); break;
    case ID::CP273: initCP273(); break;
    case ID::CP277: initCP277(); break;
    case ID::CP278: initCP278(); break;
    case ID::CP280: initCP280(); break;
    case ID::CP284: initCP284(); break;
    case ID::CP285: initCP285(); break;
    case ID::CP297: initCP297(); break;
    case ID::CP500: initCP500(); break;
    case ID::CP870: initCP870(); break;
    case ID::CP420: initCP420(); break;
    case ID::CP424: initCP424(); break;
    case ID::CP838: initCP838(); break;
    }
}

