char32_t CodePage::toUnicode(uint8_t ebcdic) const {
    uint16_t u = m_toUnicode[ebcdic];
    if (u == 0 && ebcdic != 0) return U'\xFFFD';
    return static_cast<char32_t>(u);
}

uint8_t CodePage::fromUnicode(char32_t ch) const {
    if (!m_reverseBuilt) buildReverseTable();
    if (ch > 0xFFFF) return 0x40;
    uint16_t code = static_cast<uint16_t>(ch);
    uint8_t result = m_fromUnicodeTable[code];
    return (result != 0 || code == 0) ? result : 0x40;
}

std::vector<uint8_t> CodePage::fromUnicodeString(const std::string &utf8) const {
    // Simple UTF-8 decoder + EBCDIC conversion
    std::vector<uint8_t> result;
    result.reserve(utf8.size());
    size_t i = 0;
    while (i < utf8.size()) {
        char32_t cp;
        uint8_t c = static_cast<uint8_t>(utf8[i]);
        if (c < 0x80) {
            cp = c;
            i += 1;
        } else if ((c & 0xE0) == 0xC0) {
            cp = c & 0x1F;
            if (i + 1 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+1]) & 0x3F);
            i += 2;
        } else if ((c & 0xF0) == 0xE0) {
            cp = c & 0x0F;
            if (i + 1 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+1]) & 0x3F);
            if (i + 2 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+2]) & 0x3F);
            i += 3;
        } else if ((c & 0xF8) == 0xF0) {
            cp = c & 0x07;
            if (i + 1 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+1]) & 0x3F);
            if (i + 2 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+2]) & 0x3F);
            if (i + 3 < utf8.size()) cp = (cp << 6) | (static_cast<uint8_t>(utf8[i+3]) & 0x3F);
            i += 4;
        } else {
            cp = 0xFFFD;
            i += 1;
        }
        result.push_back(fromUnicode(cp));
    }
    return result;
}

void CodePage::buildReverseTable() const {
    m_fromUnicodeTable.fill(0x00);
    for (int i = 0; i < 256; ++i) {
        uint16_t u = m_toUnicode[i];
        m_fromUnicodeTable[u] = static_cast<uint8_t>(i);
    }
    m_reverseBuilt = true;
}

